package com.scivicslab.htmlsaurus;

import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.*;

/**
 * A docs section whose directory has a numeric prefix ({@code 200_documentation}) must appear in the
 * navbar when the config names it.
 *
 * <p>The section's pages are written under the directory name without the prefix
 * ({@code documentation/}), while {@code sidebars.ts} holds the real directory name
 * ({@code dirName: '200_documentation'}). The two were compared as plain strings, so the section
 * matched no navbar item and was dropped from the navbar although its pages were built.
 */
@Tag("S1")
class NavbarNumericPrefixTest {

    @TempDir
    Path tempDir;

    private void doc(Path docs, String dir, String id) throws IOException {
        Path d = docs.resolve(dir).resolve("010_" + id);
        Files.createDirectories(d);
        Files.writeString(d.resolve("010_" + id + ".md"),
                "---\nid: " + id + "\ntitle: " + id + "\n---\n\nbody\n");
    }

    @Test
    void sectionWithNumericPrefixIsShownInNavbarInConfigOrder() throws IOException {
        Path proj = tempDir.resolve("proj");
        Path docs = proj.resolve("docs");
        doc(docs, "200_documentation", "FirstDoc");
        doc(docs, "Other", "SecondDoc");
        Files.writeString(proj.resolve("sidebars.ts"),
                "const sidebars = {\n"
                + "  documentation200Sidebar: [{type: 'autogenerated', dirName: '200_documentation'}],\n"
                + "  otherSidebar: [{type: 'autogenerated', dirName: 'Other'}],\n"
                + "};\nexport default sidebars;\n");
        Files.writeString(proj.resolve("docusaurus.config.ts"),
                "const config = { themeConfig: { navbar: { items: [\n"
                + "  {type: 'docSidebar', sidebarId: 'documentation200Sidebar', position: 'left', label: '200_documentation'},\n"
                + "  {type: 'docSidebar', sidebarId: 'otherSidebar', position: 'left', label: 'Other'},\n"
                + "] } } };\nexport default config;\n");

        BuildStages.build(docs, proj.resolve("static-html"), false);

        Path page = proj.resolve("static-html/Other/SecondDoc/index.html");
        assertTrue(Files.isRegularFile(page), "the page of the unprefixed section is built");
        String html = Files.readString(page);
        int first = html.indexOf(">200_documentation</a>");
        int second = html.indexOf(">Other</a>");
        assertTrue(first >= 0, "the prefixed section is in the navbar");
        assertTrue(second > first, "and it stands before Other, as in the config");
    }
}
